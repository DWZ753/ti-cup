/**
 * @file protocol.h
 * @brief 小车与计分显示装置之间的无线通信协议定义
 *
 * 帧格式：COBS 编码，帧头 + 数据 + 校验
 * 通信方向：小车 ↔ 计分显示装置（双向）
 */

#ifndef SHARED_PROTOCOL_H
#define SHARED_PROTOCOL_H

#include <stdint.h>

/* ================================================================
 * 帧结构
 * ================================================================ */

/** 最大数据载荷长度 */
#define PROTOCOL_PAYLOAD_MAX  64

/* ================================================================
 * 命令码
 * ================================================================ */

typedef enum {
	/* 显示装置 → 小车 */
	CMD_START      = 0x01,  /**< 启动搬运任务 */
	CMD_STOP       = 0x02,  /**< 正常停止 */
	CMD_EMERGENCY  = 0x03,  /**< 急停 */

	/* 小车 → 显示装置 */
	CMD_COUNT      = 0x10,  /**< 上报已搬运数量 */
	CMD_WEIGHT     = 0x11,  /**< 上报重量变化 */
	CMD_STATUS     = 0x12,  /**< 上报系统状态 */
	CMD_TIME       = 0x13,  /**< 上报单球搬运耗时 */
	CMD_COMPLETE   = 0x14,  /**< 全部搬运完成 */
} protocol_cmd_e;

/* ================================================================
 * 系统状态
 * ================================================================ */

typedef enum {
	STATUS_IDLE    = 0,  /**< 待命中 */
	STATUS_RUNNING = 1,  /**< 运行中 */
	STATUS_FAULT   = 2,  /**< 故障 */
} system_status_e;

/* ================================================================
 * 数据包结构
 * ================================================================ */

typedef struct {
	protocol_cmd_e cmd;                       /**< 命令码 */
	uint8_t        payload[PROTOCOL_PAYLOAD_MAX]; /**< 数据载荷 */
	uint8_t        length;                    /**< 有效载荷长度 */
} protocol_packet_t;

#endif /* SHARED_PROTOCOL_H */
